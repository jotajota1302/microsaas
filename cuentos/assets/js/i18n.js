window.cuentosLang = function () {
  const p = new URLSearchParams(location.search).get("lang");
  if (p === "en" || p === "es") return p;
  if (location.pathname.startsWith("/en")) return "en";
  return document.documentElement.lang === "en" ? "en" : "es";
};
